class EvidenceStore(Protocol):
    def observations(self, server_id: str | None = None) -> Sequence[Mapping[str, Any]]: ...


class EvidenceSource(Protocol):
    """Read-only source accepted by the local evidence exporter."""

    @property
    def store(self) -> EvidenceStore: ...

    def events(self, server_id: str | None = None) -> Sequence[Mapping[str, Any]]: ...


