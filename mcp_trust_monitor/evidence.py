"""Versioned, allowlisted local decision evidence (REQ-AUD-03).

No metadata, arguments, passages, lesson bodies, explanations or error messages
are exported. Every identifier, whether user-controlled (server, client, actor,
tool, policy and rule IDs, Senso content and model IDs) or generated by the library
(event, observation, run, call, verdict and lesson IDs), becomes a keyed pseudonym:
``pid:`` and the hex HMAC-SHA256 of the value. Its shape never exempts it.

By default each export uses a fresh random key that is never stored, so its
pseudonyms are consistent within that one export (links resolve) but cannot be
linked to another export or confirmed by guessing the identifier. An operator may
instead supply a key for stable pseudonyms across exports made with that key. No
key material or key-derived verifier is exported.

Recorded SHA-256 content digests (metadata revisions, launch identities, policy,
rules and lesson digests) are retained for traceability; anyone holding candidate
content can confirm a guess against them. Timestamps, generations, versions and
counts are retained too and can link exports. The export is pseudonymous, not
anonymous. It is evidence of recorded decisions, not proof of classification
correctness or of server receipt of a dispatched request.
"""
from __future__ import annotations

